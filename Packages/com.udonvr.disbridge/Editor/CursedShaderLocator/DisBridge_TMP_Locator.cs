using UnityEngine;
using UnityEditor;
using System.IO;
using System.Linq;

// This script runs automatically when the Unity project is loaded
[InitializeOnLoad]
public class DisBridge_TMP_Locator
{
    static DisBridge_TMP_Locator()
    {
        // We delay by one frame to ensure the AssetDatabase is ready
        EditorApplication.delayCall += GenerateIncludeFile;
    }

    static void GenerateIncludeFile()
    {
        // Find the main TextMesh Pro folder in the Assets directory
        string[] tmpFolders = AssetDatabase.FindAssets("t:folder TextMesh Pro")
            .Select(AssetDatabase.GUIDToAssetPath)
            .Where(path => path.StartsWith("Assets/"))
            .ToArray();

        if (tmpFolders.Length == 0)
        {
            // Could not find the legacy TMP folder. Maybe it's not installed.
            // You can choose to log an error or do nothing.
            Debug.LogWarning("[DisBridge] Could not find legacy TextMesh Pro folder in Assets.");
            return;
        }

        string tmpRootPath = tmpFolders[0]; // Use the first one found
        string propertiesPath = $"{tmpRootPath}/Shaders/TMPro_Properties.cginc";
        string mainIncludePath = $"{tmpRootPath}/Shaders/TMPro.cginc";

        // Define the path for our generated file inside our own package
        string packagePath = "Packages/com.udonvr.disbridge"; // Your package name
        string generatedFolderPath = $"{packagePath}/Generated";
        string generatedFilePath = $"{generatedFolderPath}/TMP_Include_Path.cginc";

        // Create the content for the generated file
        string fileContent =
$@"// This file is auto-generated by DisBridge_TMP_Locator.cs. DO NOT EDIT.
// It points to the TextMesh Pro include files found in the Assets folder.

#ifndef DISBRIDGE_TMP_INCLUDE_WRAPPER_CGINC
#define DISBRIDGE_TMP_INCLUDE_WRAPPER_CGINC

#include ""{propertiesPath}""
#include ""{mainIncludePath}""

#endif // DISBRIDGE_TMP_INCLUDE_WRAPPER_CGINC
";

        // Write the file
        // Ensure the target directory exists
        if (!Directory.Exists(generatedFolderPath))
        {
            Directory.CreateDirectory(generatedFolderPath);
        }
        File.WriteAllText(generatedFilePath, fileContent);

        // Optional: Refresh the asset database to make Unity aware of the new/changed file
        // AssetDatabase.Refresh();
    }
}